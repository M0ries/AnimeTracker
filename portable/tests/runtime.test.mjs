import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {loadPyodide} from 'pyodide';
import 'fake-indexeddb/auto';
import {createRuntime} from '../runtime.mjs';
import {BrowserStorage} from '../storage.mjs';
const root=new URL('../../',import.meta.url);
const options={loadPyodide,indexURL:fileURLToPath(new URL('node_modules/pyodide/',root)),storeSource:await readFile(new URL('local_app/store.py',root),'utf8'),apiSource:await readFile(new URL('../api.py',import.meta.url),'utf8')};
const persistent=new BrowserStorage();let fail=false;
const storage={load:()=>persistent.load(),save:(files,revision)=>{if(fail)throw Error('simulated disk failure');return persistent.save(files,revision);}};
const runtime=await createRuntime({...options,storage});
assert.equal((await runtime.call('state')).anime.length,0);
const {id}=await runtime.call('anime/save',{data:{name:'合成测试',status:'watching',total_episodes:12}});
const round=await runtime.call('round/save',{anime_id:id,data:{kind:'first',status:'watching',started_at:'2026-01-01',progress:0}});
await runtime.call('session/add',{round_id:round.id,data:{episode:1,watched_at:'2026-01-02',notes:'测试'}});
const before=await runtime.call('state');assert.equal(before.anime.length,1);assert.equal(before.sessions.length,1);
fail=true;
await assert.rejects(runtime.call('anime/save',{data:{name:'must roll back'}}),/simulated disk failure/);
assert.deepEqual((await runtime.call('state')).anime,before.anime);
fail=false;
await Promise.all([runtime.call('anime/save',{data:{name:'serialized A'}}),runtime.call('anime/save',{data:{name:'serialized B'}})]);
assert.equal((await runtime.call('state')).anime.length,3);
const full=JSON.parse((await runtime.call('export/json')).content);
assert.equal(full.tables.anime.length,3);
assert.ok((await runtime.call('export/csv')).content.length>0);
assert.ok((await runtime.call('template.csv')).content.includes('name'));
const backup=await runtime.call('backup');assert.equal(Buffer.from(backup.base64,'base64').subarray(0,16).toString(),'SQLite format 3\0');
await runtime.call('delete',{table:'anime',id,confirm:true});assert.equal((await runtime.call('state')).anime.length,2);
await runtime.call('restore',{base64:backup.base64,confirm:true});assert.equal((await runtime.call('state')).anime.length,3);
assert.deepEqual((await runtime.call('state')).sessions,before.sessions);
await assert.rejects(runtime.call('restore',{base64:Buffer.from('not database').toString('base64'),confirm:true}));
assert.equal((await runtime.call('state')).anime.length,3);
const restored=await createRuntime({...options,storage:new BrowserStorage()});
assert.deepEqual((await restored.call('state')).anime,(await runtime.call('state')).anime);
await restored.call('anime/save',{data:{name:'other window'}});
await assert.rejects(runtime.call('anime/save',{data:{name:'stale writer'}}),/其他窗口/);
assert.equal((await runtime.call('state')).anime.length,3);
assert.equal((await restored.call('state')).anime.length,4);
// Round-trip a full export into an empty library, preserving IDs and dates.
let snap={revision:0,files:{}};
const fresh=await createRuntime({...options,storage:{load:async()=>snap,save:async(files,revision)=>(snap={files,revision:revision+1})}});
await fresh.call('import/json',{document:full});
assert.deepEqual(JSON.parse((await fresh.call('export/json')).content).tables.anime,full.tables.anime);
assert.deepEqual((await fresh.call('state')).sessions,full.tables.sessions);
const result=await fresh.call('import/json',{document:full});assert.equal(result.imported,0);
console.log('PASS: WASM SQLite, CRUD, dates, JSON/CSV export, backup/restore, durable reload, concurrent writes, rollback and stale-window protection');
